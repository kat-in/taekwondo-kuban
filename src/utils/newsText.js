// Новости в списке показываются коротким preview, который обрезается
// несколькими строками. Раньше там рендерился markdown, и если в тексте
// есть ссылка, получалась вложенная <a> внутри <a> — карточка целиком
// обёрнута в Link. Поэтому в списке markdown не рендерим, а превращаем
// в обычный текст. На странице самой новости markdown остаётся.
const toPlainText = (markdown) =>
  String(markdown || '')
    // ![картинка](ссылка) → ничего: в preview картинки не нужны
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '')
    // [текст](ссылка) → текст
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    // <https://…> → сама ссылка
    .replace(/<(https?:\/\/[^>\s]+)>/g, '$1')
    // **жирный** и *курсив*. Подчёркивание не трогаем: в словах оно встречается
    // как обычный символ, а курсива в новостях всё равно нет.
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\*(?!\s)(.+?)(?<!\s)\*/g, '$1')
    // `код`
    .replace(/`([^`]*)`/g, '$1')
    // заголовки, цитаты и пункты списка
    .replace(/^\s{0,3}#{1,6}\s+/gm, '')
    .replace(/^\s{0,3}>\s?/gm, '')
    .replace(/^\s{0,3}[-*+]\s+/gm, '')
    // переносы строк в preview не нужны: текст идёт одной простынёй
    .replace(/\s+/g, ' ')
    .trim()

export default toPlainText
